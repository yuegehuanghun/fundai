async function queryTertiary(code) {
  console.log(`[FundLookup:3/4] 🔍 第三数据源(东方财富搜索): ${code}`);
  try {
    // 优先用 fund-api.js 提供的 jsonpCb（JSONP bypass CORS）
    if (typeof jsonpCb === 'function') {
      const url = `https://fundsuggest.eastmoney.com/fundsearch/api/FundSearchAPI.ashx?m=1&key=${code}`;
      const data = await jsonpCb(url, 5000, 'callback');
      if (data && data.Datas && data.Datas.length > 0) {
        const item = data.Datas[0];
        const name = item.NAME || item.SHORTNAME || item.FUNDNAME || '';
        if (name) {
          console.log(`[FundLookup:3/4] ✅ 东财搜索 JSONP 成功: ${code} → ${name}`);
          return { name, code, source: 'eastmoney_search' };
        }
      }
      if (data && data.Errcode !== undefined && data.Errcode !== 0) {
        console.warn(`[FundLookup:3/4] ⚠️ 东财搜索 API 返回错误: ${code} errcode=${data.Errcode}`);
      }
    }

    // JSONP 不可用或失败 → 降级用 fetch（可能触发 CORS 错误，由 catch 静默处理）
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 4000);
    const resp = await fetch(
      `https://fundsuggest.eastmoney.com/fundsearch/api/FundSearchAPI.ashx?m=1&key=${code}`,
      { signal: controller.signal }
    );
    clearTimeout(timeout);
    if (!resp.ok) return null;
    const result = await resp.json();
    if (result && result.Datas && result.Datas.length > 0) {
      const item = result.Datas[0];
      const name = item.NAME || item.SHORTNAME || item.FUNDNAME || '';
      if (name) {
        console.log(`[FundLookup:3/4] ✅ 东财搜索 fetch 成功: ${code} → ${name}`);
        return { name, code, source: 'eastmoney_search' };
      }
    }
    return null;
  } catch (err) {
    console.warn(`[FundLookup:3/4] ❌ 东财搜索失败: ${code} | ${err.message}`);
    return null;
  }
}

