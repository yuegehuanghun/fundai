/**
 * 查询基金名称（4 层兜底机制）
 *
 * 优先级:
 *   1. 内存缓存（10 秒内）
 *   2. localStorage 永久缓存
 *   3. 主数据源 — 天天基金 JSONP（3 秒超时）
 *   4. 备用数据源 — 东方财富详情 JS（含 A/C 后缀兼容）
 *   5. 第三数据源 — 东方财富搜索 suggest API
 *   6. 本地离线库 — 内置 ~1500 只基金代码库
 *   7. 返回 null → UI 层允许手动输入名称
 */
async function lookupFundName(code) {
  // 输入校验
  if (!code || !/^\d{6}$/.test(code)) {
    return null;
  }

  // 1. 内存缓存
  const memCached = getMemCache(code);
  if (memCached) {
    console.log(`[FundLookup] 💾 内存缓存命中: ${code} → ${memCached.name}`);
    return memCached;
  }

  // 2. localStorage 缓存
  const localCached = getCachedName(code);
  if (localCached) {
    console.log(`[FundLookup] 💾 本地缓存命中: ${code} → ${localCached.name}`);
    setMemCache(code, localCached);
    return localCached;
  }

  let result = null;
  let allOnlineFailed = false;

  // 3. 主数据源（层级 1）
  result = await queryPrimary(code);

  // 4. 备用数据源（层级 2）
  if (!result) {
    result = await querySecondary(code);
  }

  // 5. 第三数据源（层级 3）
  if (!result) {
    result = await queryTertiary(code);
    if (!result) {
      allOnlineFailed = true;
    }
  }

  // 6. 本地离线库兜底（层级 4）
  if (!result) {
    result = queryLocal(code);
    if (result) {
      result._fromLocalDB = true; // 标记来自本地库
    }
  }

  if (result) {
    // 推断基金类型
    if (!result.type) {
      result.type = inferFundType(result.name);
    }

    // 写入缓存
    setLocalCache(code, result);
    setMemCache(code, result);

    if (result._fromLocalDB) {
      console.log(`[FundLookup] 🎯 最终结果(本地库兜底): ${code} → ${result.name} (${result.type})`);
    } else {
      console.log(`[FundLookup] 🎯 最终结果: ${code} → ${result.name} (${result.type}, 来源: ${result.source})`);
    }
    return result;
  }

  // 7. 全部失败 — 返回 null，UI 层展示手动输入
  console.warn(`[FundLookup] ❌ 全部4层查询均未匹配: ${code}（将允许手动输入名称）`);
  return null;
}

/**
 * 带防抖的输入监听处理
 * 仅供基金录入表单使用
 */
const FundLookupInput = {
  _timer: null,
  _lastCode: '',

  /**
   * 处理输入变化（由 UI 层绑定到 input 事件）
   * @param {string} rawInput - 输入框原始值
   * @param {Object} callbacks - { onStart, onSuccess, onError, onNotFound }
   */
  handleInput(rawInput, callbacks = {}) {
    // 过滤: 只保留数字，最多6位
    const filtered = rawInput.replace(/\D/g, '').slice(0, 6);
    FundLookupInput._lastCode = filtered;

    // 清除之前的定时器
    if (FundLookupInput._timer) {
      clearTimeout(FundLookupInput._timer);
    }

    // 不足 6 位: 不发起请求，清除反馈
    if (filtered.length < 6) {
      if (callbacks.onClear) callbacks.onClear();
      return filtered;
    }

    // 6 位: 300ms 防抖后查询
    if (callbacks.onStart) callbacks.onStart(filtered);

    FundLookupInput._timer = setTimeout(async () => {
      // 再次确认代码未变化
      if (FundLookupInput._lastCode !== filtered) return;

      const code = filtered;
      console.log(`[FundLookup] 🚀 开始查询: ${code}`);

      try {
        const result = await lookupFundName(code);

        if (result && result.source !== 'local_db') {
          // 接口查询成功
          if (callbacks.onSuccess) callbacks.onSuccess(result);
        } else if (result && result.source === 'local_db') {
          // 本地库兜底成功
          if (callbacks.onSuccess) callbacks.onSuccess(result);
          if (callbacks.onFallback) callbacks.onFallback(result);
        } else {
          // 完全未匹配
          if (callbacks.onNotFound) callbacks.onNotFound(code);
        }
      } catch (err) {
        console.error(`[FundLookup] ❌ 查询异常: ${code}`, err);
        // 最后一次尝试本地库
        const localResult = queryLocal(code);
        if (localResult) {
          localResult.type = inferFundType(localResult.name);
          setLocalCache(code, localResult);
          setMemCache(code, localResult);
          if (callbacks.onSuccess) callbacks.onSuccess(localResult);
          if (callbacks.onFallback) callbacks.onFallback({ ...localResult, error: err.message });
        } else {
          if (callbacks.onError) callbacks.onError(err.message);
        }
      }
    }, 300);

    return filtered;
  },

  /** 清理 */
  cleanup() {
    if (FundLookupInput._timer) {
      clearTimeout(FundLookupInput._timer);
      FundLookupInput._timer = null;
    }
  },
};
